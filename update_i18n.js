function inject(path, keysStr) {
    let content = fs.readFileSync(path, 'utf8');
    if (content.includes('// Language')) {
        let parts = content.split('// Language');
        fs.writeFileSync(path, parts[0] + keysStr + '\n  // Language' + parts[1]);
    } else if (content.includes('// ── Language')) {
        let parts = content.split('// ── Language');
        fs.writeFileSync(path, parts[0] + keysStr + '\n  // ── Language' + parts[1]);
    }
}

